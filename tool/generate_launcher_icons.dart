// Regenerate Android launcher artwork with:
// flutter test --no-pub tool/generate_launcher_icons.dart
import 'dart:io';
import 'dart:ui' as ui;

import 'package:flutter_svg/flutter_svg.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:image/image.dart' as img;

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();
  test('generate circular launcher artwork from the existing vector mark', () async {
    final original = await File(
      'assets/branding/nexmusic-logo.svg',
    ).readAsString();
    const whiteCircle = '<circle cx="256" cy="256" r="256" fill="#FFFFFF"/>';
    const launcherCircles =
        '''<circle cx="256" cy="256" r="256" fill="#E8D9FF"/>
  <circle cx="256" cy="256" r="200" fill="#FFFFFF" stroke="#BFA1E0" stroke-width="5"/>
  <g transform="translate(56 56) scale(0.78125)">''';
    if (!original.contains(whiteCircle)) {
      throw StateError(
        'The source logo circle changed; update the launcher generator.',
      );
    }
    final svg = original
        .replaceFirst(whiteCircle, launcherCircles)
        .replaceFirst('</svg>', '  </g>\n</svg>');
    await File('assets/branding/nexmusic-launcher.svg').writeAsString(svg);

    final picture = await vg.loadPicture(SvgStringLoader(svg), null);
    final raster = await picture.picture.toImage(512, 512);
    final bytes = (await raster.toByteData(
      format: ui.ImageByteFormat.png,
    ))!.buffer.asUint8List();
    await File('assets/branding/nexmusic-launcher.png').writeAsBytes(bytes);
    final decoded = img.decodePng(bytes)!;
    for (final density in {
      'mdpi': 48,
      'hdpi': 72,
      'xhdpi': 96,
      'xxhdpi': 144,
      'xxxhdpi': 192,
    }.entries) {
      final icon = img.copyResize(
        decoded,
        width: density.value,
        height: density.value,
        interpolation: img.Interpolation.average,
      );
      await File(
        'android/app/src/main/res/mipmap-${density.key}/ic_launcher.png',
      ).writeAsBytes(img.encodePng(icon));
    }
    raster.dispose();
    picture.picture.dispose();

    final native = await File(
      'android/app/src/main/res/drawable/nexmusic_logo.xml',
    ).readAsString();
    const nativeCircle =
        '<path android:fillColor="#FFFFFFFF" android:pathData="M256,0A256,256 0,1 1,256,512A256,256 0,1 1,256,0Z" />';
    if (!native.contains(nativeCircle)) {
      throw StateError(
        'The native logo circle changed; update the launcher generator.',
      );
    }
    final launcher = native
        .replaceFirst(
          '<!-- Vector counterpart of assets/branding/nexmusic-logo.svg. -->',
          '<!-- Generated by tool/generate_launcher_icons.dart; launcher artwork only. -->',
        )
        .replaceFirst(
          nativeCircle,
          '''<path android:fillColor="#FFE8D9FF" android:pathData="M256,0A256,256 0,1 1,256,512A256,256 0,1 1,256,0Z" />
    <path android:fillColor="#FFFFFFFF" android:strokeColor="#FFBFA1E0" android:strokeWidth="5"
        android:pathData="M256,56A200,200 0,1 1,256,456A200,200 0,1 1,256,56Z" />
    <group android:translateX="56" android:translateY="56" android:scaleX="0.78125" android:scaleY="0.78125">''',
        )
        .replaceFirst('</vector>', '    </group>\n</vector>');
    await File(
      'android/app/src/main/res/drawable/nexmusic_launcher_logo.xml',
    ).writeAsString(launcher);
  });
}
